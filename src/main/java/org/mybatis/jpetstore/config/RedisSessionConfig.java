package org.mybatis.jpetstore.config;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.data.redis.connection.RedisPassword;
import org.springframework.data.redis.connection.RedisStandaloneConfiguration;
import org.springframework.data.redis.connection.lettuce.LettuceClientConfiguration;
import org.springframework.data.redis.connection.lettuce.LettuceConnectionFactory;
import org.springframework.session.data.redis.config.ConfigureRedisAction;
import org.springframework.session.data.redis.config.annotation.web.http.EnableRedisHttpSession;

/**
 * Externalizes HTTP session state to Google Cloud Memorystore for Redis (Spring Session), so that application
 * instances are stateless and sessions survive instance restarts and load balancing.
 *
 * <p>
 * Configuration is read from environment variables:
 * </p>
 * <ul>
 * <li>{@code REDIS_HOST} - Memorystore instance host (default: localhost)</li>
 * <li>{@code REDIS_PORT} - Memorystore instance port (default: 6379)</li>
 * <li>{@code REDIS_PASSWORD} - AUTH string, if AUTH is enabled (optional)</li>
 * <li>{@code REDIS_SSL} - set to "true" to enable in-transit encryption (default: false)</li>
 * <li>{@code SESSION_TIMEOUT_SECONDS} - session inactivity timeout (default: 1800)</li>
 * <li>{@code SESSION_REDIS_NAMESPACE} - key namespace (default: jpetstore:session)</li>
 * </ul>
 */
@Configuration
@EnableRedisHttpSession(maxInactiveIntervalInSeconds = 1800, redisNamespace = "jpetstore:session")
public class RedisSessionConfig {

  private static String env(String name, String defaultValue) {
    String value = System.getenv(name);
    return value == null || value.trim().isEmpty() ? defaultValue : value.trim();
  }

  /**
   * Redis connection factory pointing to Memorystore for Redis.
   *
   * @return the connection factory
   */
  @Bean
  public LettuceConnectionFactory redisConnectionFactory() {
    RedisStandaloneConfiguration config = new RedisStandaloneConfiguration(env("REDIS_HOST", "localhost"),
        Integer.parseInt(env("REDIS_PORT", "6379")));
    String password = System.getenv("REDIS_PASSWORD");
    if (password != null && !password.isEmpty()) {
      config.setPassword(RedisPassword.of(password));
    }
    LettuceClientConfiguration.LettuceClientConfigurationBuilder builder = LettuceClientConfiguration.builder();
    if (Boolean.parseBoolean(env("REDIS_SSL", "false"))) {
      builder.useSsl();
    }
    return new LettuceConnectionFactory(config, builder.build());
  }

  /**
   * Managed Redis services (Memorystore) disable the CONFIG command, so skip keyspace notification setup.
   *
   * @return a no-op action
   */
  @Bean
  public static ConfigureRedisAction configureRedisAction() {
    return ConfigureRedisAction.NO_OP;
  }
}
